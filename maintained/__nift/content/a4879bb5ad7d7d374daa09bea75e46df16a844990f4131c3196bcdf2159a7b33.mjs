 localTracks.videoTrack?.unpipe();
 localTracks.videoTrack?.close();
 compositor?.unpipe();
 vbProcessor?.unpipe();
 sourceVideoTrack1?.unpipe();
 sourceVideoTrack1?.close();
 sourceVideoTrack2?.unpipe();
 sourceVideoTrack2?.close();
