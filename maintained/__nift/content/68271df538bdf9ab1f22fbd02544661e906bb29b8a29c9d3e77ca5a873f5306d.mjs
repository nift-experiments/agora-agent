    payload = {
        "name": "<agent_name>",
        "pipeline_id": "<pipeline_id>",
        "properties": {
            "channel": "<channel_name>",
            "agent_rtc_uid": "<agent_rtc_uid>",
            "remote_rtc_uids": ["*"],
            "token": "<token>"
        }
    }

    headers = {
        "Content-Type": "application/json",
        "Authorization": "Basic <base64Credentials>"
    }

